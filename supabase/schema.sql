-- Esquema de la base de datos (Supabase / PostgreSQL).
-- Documenta lo que ya se ejecutó en el SQL Editor del proyecto; sirve para recrearlo en un proyecto nuevo.
-- Seguridad: el proyecto tiene RLS automático, así que cada tabla nace cerrada. Las policies de abajo
-- solo permiten AÑADIR filas desde la web (rol anon). Nadie puede leer, cambiar ni borrar con la clave pública;
-- los novios ven los datos desde el panel de Supabase.

-- Canciones sugeridas para el DJ
create table public.song_suggestions (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  guest_name text not null check (length(trim(guest_name)) > 0),
  song text not null check (length(trim(song)) > 0),
  youtube_url text
);

create policy "Invitados pueden sugerir canciones"
on public.song_suggestions for insert to anon with check (true);

-- Confirmaciones: un grupo por envío del formulario…
create table public.rsvp_groups (
  id uuid primary key, -- lo genera la web (crypto.randomUUID) para enlazar a las personas sin tener que leer
  created_at timestamptz not null default now(),
  attendance text not null check (attendance in ('yes', 'no')),
  declined_names text,
  message text,
  has_consent boolean not null default false,
  check (attendance = 'yes' or length(trim(declined_names)) > 0),
  check (attendance = 'no' or has_consent = true)
);

-- …y una fila por persona que asiste (para el catering)
create table public.rsvp_guests (
  id uuid primary key default gen_random_uuid(),
  created_at timestamptz not null default now(),
  group_id uuid not null references public.rsvp_groups (id) on delete cascade,
  name text not null check (length(trim(name)) > 0),
  age_group text not null check (age_group in ('adult', 'child')),
  diet text not null check (diet in ('none', 'vegetarian', 'vegan')),
  has_allergies boolean not null,
  allergies text not null default '',
  check (has_allergies = false or length(trim(allergies)) > 0)
);

create policy "Invitados pueden confirmar asistencia"
on public.rsvp_groups for insert to anon with check (true);

create policy "Invitados pueden añadir personas a su confirmación"
on public.rsvp_guests for insert to anon with check (true);
